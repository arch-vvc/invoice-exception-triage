# ---------------------------------------------------------------- reading the files


def text(name: str) -> str:
    raw = (SAMPLE / name).read_bytes()
    assert not raw.startswith(b"\xef\xbb\xbf"), f"{name} has a BOM"
    assert b"\r" not in raw, f"{name} has carriage returns"
    return raw.decode("utf-8")  # strict: raises on bad UTF-8


def lines(name: str) -> list[str]:
    return text(name).split("\n")[:-1]  # the file ends with a newline


def parse_line(line: str) -> list[str]:
    assert line.count('"') % 2 == 0, f"multi-line cell suspected: {line[:60]}"
    return next(csv.reader([line]))


def table(name: str, header_line: int):
    """Return (header, [(physical line number, {column: cell})]) skipping blank rows and the Grand Total footer."""
    all_lines = lines(name)
    header = parse_line(all_lines[header_line - 1])
    rows = []
    for n, line in enumerate(all_lines[header_line:], start=header_line + 1):
        cells = parse_line(line)
        if not any(c.strip() for c in cells) or any("total" in c.lower() for c in cells):
            continue
        assert len(cells) == len(header), f"{name} line {n}: {len(cells)} cells, expected {len(header)}"
        rows.append((n, dict(zip(header, cells, strict=True))))
    return header, rows


def invoices():
    return table("invoices.csv", 4)[1]


def pos():
    return table("purchase_orders.csv", 2)[1]


def payments():
    return table("payments.csv", 2)[1]


def key_rows():
    all_lines = lines("expected_exceptions.csv")
    header = parse_line(all_lines[0])
    return [dict(zip(header, parse_line(line), strict=True)) for line in all_lines[1:]]


# ---------------------------------------------------------------- independent copies of the contract rules


def parse_amount(cell: str) -> Decimal | None:
    s = cell.strip()
    if s in ("", "-", "NA"):
        return None
    negative = s.startswith("(") and s.endswith(")")
    s = s.strip("()")
    s = re.sub(r"(₹|Rs\.?|INR|Dr|Cr)", "", s).replace(",", "").strip()
    value = Decimal(s)  # raises if the cell is something the contract does not list
    return -value if negative else value


def parse_gst_rate(cell: str) -> Decimal:
    match = re.fullmatch(r"(?:IGST )?(\d+(?:\.\d+)?)\s?%?", cell.strip())
    assert match, f"unparseable GST rate {cell!r}"
    return Decimal(match.group(1))


def doc_key(s: str) -> str:
    tokens = [t for t in re.split(r"[^A-Z0-9]+", s.upper()) if t]
    return "".join(re.sub(r"\d+", lambda m: m.group().lstrip("0") or "0", t) for t in tokens)


def vendor_key(name: str) -> str:
    s = re.sub(r"^M\s*/\s*S\.?\s+", "", name.upper())
    s = re.sub(r"[^A-Z0-9]+", " ", s.replace("&", " AND "))
    drop = {"PVT", "PRIVATE", "LTD", "LIMITED", "LLP", "CO", "COMPANY", "INC", "THE", "MS"}
    return " ".join(t for t in s.split() if t not in drop)


CHARS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
GSTIN_RE = re.compile(r"^(0[1-9]|[1-2][0-9]|3[0-8])[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$")


def gstin_problem(g: str) -> str | None:
    g = g.replace(" ", "").upper()
    if not g:
        return "missing"
    if not GSTIN_RE.match(g):
        return "format"
    total = 0
    for i, ch in enumerate(g[:14]):
        p = CHARS.index(ch) * (1 if i % 2 == 0 else 2)
        total += p // 36 + p % 36
    return None if CHARS[(36 - total % 36) % 36] == g[14] else "checksum"


def tol(reference: Decimal) -> Decimal:
    return max(Decimal(1), Decimal("0.01") * abs(reference))


