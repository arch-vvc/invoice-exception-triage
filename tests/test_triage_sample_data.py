def test_quantity_and_gst_rate_formats_are_used():
    qty = column_cells({"i": invoices(), "p": pos()}, {"i": ["Billed Qty"], "p": ["Quantity"]})
    assert formats_seen(QTY_PATTERNS, qty) == set(QTY_PATTERNS)
    rates = column_cells({"i": invoices(), "p": pos()}, {"i": ["GST %"], "p": ["Tax %"]})
    assert formats_seen(GST_PATTERNS, rates) == set(GST_PATTERNS)
    assert {parse_gst_rate(c) for c in rates} <= SLABS


def test_optional_cells_are_left_blank_and_required_ones_are_not():
    optional = {
        "invoices": ["Particulars", "Rate", "Tax Amount", "Order No"],
        "purchase_orders": ["PO Date", "Sub Total"],
        "payments": ["Txn Date", "TDS Deducted", "Mode", "UTR No", "Against Bill"],
    }
    sources = {"invoices": invoices(), "purchase_orders": pos(), "payments": payments()}
    blanks = 0
    for name, rows in sources.items():
        for n, cells in rows:
            for column, cell in cells.items():
                if not cell.strip():
                    assert column in optional[name], f"{name} line {n}: required column {column!r} is blank"
                    blanks += 1
    assert blanks >= 4
    for column in optional["purchase_orders"] + ["Rate", "Tax Amount"]:
        assert any(not cells.get(column, "x").strip() for _, cells in pos() + invoices())


# ---------------------------------------------------------------- consistency of the numbers


def test_each_invoice_total_is_taxable_plus_gst_within_fifty_paise():
    rounded = 0
    for n, c in invoices():
        taxable, total = parse_amount(c["Taxable Value"]), parse_amount(c["Invoice Amount"])
        rate = parse_gst_rate(c["GST %"])
        gst = parse_amount(c["Tax Amount"])
        if gst is not None:
            assert abs(gst - taxable * rate / 100) <= Decimal("0.01"), f"line {n}"
        exact = taxable + (gst if gst is not None else taxable * rate / 100)
        assert abs(total - exact) <= Decimal("0.50"), f"line {n}"
        rounded += total != exact
    assert rounded >= 3  # totals rounded off by up to 50 paise are present


def linked_payments():
    """Independent version of the C3 payment linking: returns {invoice_no: [settled amounts]}."""
    firsts: dict[str, dict] = {}
    for _, c in invoices():
        firsts.setdefault(doc_key(c["Bill Number"]), c)
    by_invoice: dict[str, list[Decimal]] = {}
    for n, p in payments():
        settled = parse_amount(p["Amount Paid"]) + (parse_amount(p["TDS Deducted"]) or 0)
        if p["Against Bill"].strip():
            target = firsts[doc_key(p["Against Bill"])]
        else:
            matches = [
                c for c in firsts.values()
                if vendor_key(c["Party Name"]) == vendor_key(p["Paid To"])
                and abs(parse_amount(c["Invoice Amount"]) - settled) <= tol(settled)
            ]  # fmt: skip
            assert len(matches) == 1, f"payment line {n} has no unique match"
            target = matches[0]
        by_invoice.setdefault(target["Bill Number"], []).append(settled)
    return firsts, by_invoice


def test_payments_settle_in_full_except_the_planted_ones():
    firsts, by_invoice = linked_payments()
    total_of = {c["Bill Number"]: parse_amount(c["Invoice Amount"]) for c in firsts.values()}
    partial, over = set(), set()
    for no, settled in by_invoice.items():
        gap = sum(settled) - total_of[no]
        if gap < -1:
            partial.add(no)
        elif gap > 1:
            over.add(no)
    key = key_rows()
    assert partial == {r["invoice_no"] for r in key if r["exception_type"] == "partial_payment"}
    assert over == {r["invoice_no"] for r in key if r["exception_type"] == "overpayment"}


def test_duplicates_in_the_file_are_exactly_the_keyed_duplicates():
    seen: dict[tuple[str, str], Decimal] = {}
    dups = set()
    for _, c in invoices():
        k = (vendor_key(c["Party Name"]), doc_key(c["Bill Number"]))
        total = parse_amount(c["Invoice Amount"])
        if k in seen and abs(total - seen[k]) <= tol(seen[k]):
            dups.add(c["Bill Number"])
        seen.setdefault(k, total)
    assert dups == {r["invoice_no"] for r in key_rows() if r["exception_type"] == "duplicate_invoice"}
    assert {"INV/42", "SE-24-25-107"} == dups


# ---------------------------------------------------------------- traps that must not fire


def test_traps_are_present():
    inv, po, pay = invoices(), pos(), payments()

    # M/s. Kumar Packaging Pvt. Ltd. on the PO against KUMAR PACKAGING PRIVATE LIMITED on the invoice
    po_names = {c["Vendor Name"] for _, c in po}
    inv_names = {c["Party Name"] for _, c in inv}
    assert "M/s. Kumar Packaging Pvt. Ltd." in po_names and "KUMAR PACKAGING PRIVATE LIMITED" in inv_names
    assert vendor_key("M/s. Kumar Packaging Pvt. Ltd.") == "KUMAR PACKAGING"
    assert vendor_key("KUMAR PACKAGING PRIVATE LIMITED") == "KUMAR PACKAGING"

    # a blank Order No whose vendor has exactly one PO, and one more whose vendor has none
    blank = [c for _, c in inv if not c["Order No"].strip()]
    assert len(blank) == 2
    po_count = {}
    for _, c in po:
        po_count[vendor_key(c["Vendor Name"])] = po_count.get(vendor_key(c["Vendor Name"]), 0) + 1
    assert sorted(po_count.get(vendor_key(c["Party Name"]), 0) for c in blank) == [0, 1]

    # one payment with a blank Against Bill
    assert sum(1 for _, p in pay if not p["Against Bill"].strip()) == 1

    # 3 or more payments with TDS, invoices paid in two instalments
    assert sum(1 for _, p in pay if parse_amount(p["TDS Deducted"])) >= 3
    _, by_invoice = linked_payments()
    assert sum(1 for settled in by_invoice.values() if len(settled) == 2) >= 2

    # 3 or more POs billed across two invoices, within quantity
    billed: dict[str, list[Decimal]] = {}
    for _, c in inv:
        if c["Order No"].strip() and c["Bill Number"] not in {"INV/42", "SE-24-25-107"}:
            billed.setdefault(doc_key(c["Order No"]), []).append(parse_amount(re.sub(r"[^\d.,]", "", c["Billed Qty"])))
    ordered = {doc_key(c["PO#"]): parse_amount(re.sub(r"[^\d.,]", "", c["Quantity"])) for _, c in po}
    within = [k for k, qs in billed.items() if k in ordered and len(qs) == 2 and sum(qs) <= ordered[k]]
    assert len(within) >= 3


# ---------------------------------------------------------------- determinism


def load_generator():
    spec = importlib.util.spec_from_file_location("sample_generate", SAMPLE / "generate.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module  # dataclasses looks its own module up here
    spec.loader.exec_module(module)
    return module


def test_generator_is_deterministic(tmp_path):
    generator = load_generator()
    first, second = tmp_path / "a", tmp_path / "b"
    generator.main(["--out", str(first)])
    generator.main(["--out", str(second)])
    for name in FILES:
        assert (first / name).read_bytes() == (second / name).read_bytes(), name
        assert (first / name).read_bytes() == (SAMPLE / name).read_bytes(), f"{name} is stale, rerun generate.py"


def test_generator_uses_no_random_module():
    source = (SAMPLE / "generate.py").read_text(encoding="utf-8")
    assert not re.search(r"^\s*(import|from)\s+random\b", source, re.MULTILINE)
