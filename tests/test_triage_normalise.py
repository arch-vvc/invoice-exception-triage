def gstin_check_char(first14: str) -> str:
    """Independent copy of the C2 algorithm, so the test does not trust the code under test."""
    chars = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    total = 0
    for i, ch in enumerate(first14):
        p = chars.index(ch) * (1 if i % 2 == 0 else 2)
        total += p // 36 + p % 36
    return chars[(36 - total % 36) % 36]


def test_known_valid_gstins_pass():
    for gstin in (VALID_GSTIN, OTHER_VALID_GSTIN):
        assert gstin[14] == gstin_check_char(gstin[:14])
        assert gstin_problem(gstin) is None


def test_gstin_is_cleaned_before_checking():
    assert gstin_problem(" 27abcde 1234f1z0 ") is None


def test_gstin_bad_checksum():
    assert gstin_problem("27ABCDE1234F1Z1") == "checksum"


def test_gstin_bad_format():
    assert gstin_problem("27ABCDE1234F1Z") == "format"
    assert gstin_problem("99ABCDE1234F1Z0") == "format"
    assert gstin_problem("27ABCDE12345F1Z") == "format"


