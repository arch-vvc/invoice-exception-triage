@dataclass(frozen=True)
class Pay:
    inv: str  # invoice ref
    lag: int  # days after the invoice date
    amount: Decimal | None = None  # None: pay the whole invoice less TDS
    tds_pct: int = 0
    mode: str = "NEFT"
    bill: str | None = None  # Against Bill cell; None copies the invoice number, "" leaves it blank
    astyle: str = "in2"
    tstyle: str = ""  # TDS cell style; "" leaves it empty, "-" writes a dash
    dstyle: str = "dmy/"
    blank: tuple[str, ...] = ()  # optional cells left empty: date, mode, utr


def pay(inv_ref, lag, amount=None, **kw) -> Pay:
    return Pay(inv_ref, lag, None if amount is None else D(amount), **kw)


