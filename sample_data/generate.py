def invoice_cells(i: Invoice) -> list[str]:
    s_taxable, s_gst, s_total = i.styles
    return [
        date_cell(i.day, i.dstyle),
        i.no,
        i.party,
        i.gstin_cell,
        i.po_cell,
        "" if "item" in i.blank else i.item,
        qty_cell(i.qty, i.unit, i.qstyle),
        cell_money(i.rate, i.rstyle),
        money(i.taxable, s_taxable),
        gst_cell(i.gst, i.gstyle),
        cell_money(i.gst_amount, s_gst),
        money(i.total, s_total),
    ]


def po_cells(p: PO) -> list[str]:
    return [
        p.no,
        VENDORS[p.vendor].po_name,
        "" if "po_date" in p.blank else date_cell(p.day, p.dstyle),
        p.item,
        qty_cell(p.qty, p.unit, p.qstyle),
        money(p.rate, p.rstyle),
        "" if "amount" in p.blank else money(p.amount, p.astyle),
        gst_cell(p.gst, p.gstyle),
        VENDORS[p.vendor].gstin,
    ]


def payment_cells(k: int, row, by_ref) -> list[str]:
    pid, d, pm, amount_paid, tds = row
    i = by_ref[pm.inv]
    utr = f"{UTR_BANKS[k % 4]}{d:%y%m%d}{481000 + 137 * k:06d}"
    assert pm.tstyle or not tds, f"{pid}: a TDS amount must be shown"
    return [
        "" if "date" in pm.blank else date_cell(d, pm.dstyle),
        pid,
        VENDORS[i.vendor].payee,
        i.no if pm.bill is None else pm.bill,
        money(amount_paid, pm.astyle),
        cell_money(tds, pm.tstyle),
        "" if "mode" in pm.blank else pm.mode,
        "" if "utr" in pm.blank or pm.mode == "Reversal" else utr,
    ]


def planted_note(f: Found, pos_by_no: dict[str, PO]) -> str:
    i, p = f.invoice, pos_by_no.get(f.po_no)
    if f.type == "amount_mismatch":
        return f"SYNTHETIC: vendor billed {money(i.rate, 'in2')} a unit against a PO rate of {money(p.rate, 'in2')}, more than 3 percent over."
    if f.type == "quantity_mismatch":
        return f"SYNTHETIC: billing runs past the PO quantity of {p.qty:,.0f} {p.unit}."
    if f.type == "duplicate_invoice":
        return f"SYNTHETIC: same vendor and same bill as {f.note}, rewritten with different separators."
    if f.type == "missing_po":
        why = (
            f"Order No is blank and {i.party} has no PO on file"
            if not i.po_cell.strip()
            else f"Order No {i.po_cell} does not exist in the PO file"
        )
        return f"SYNTHETIC: {why}."
    if f.type == "partial_payment":
        return "SYNTHETIC: only part of the invoice has been paid and no further payment is on file."
    if f.type == "overpayment":
        return "SYNTHETIC: the invoice was paid twice by two separate bank transfers."
    if f.type == "vendor_name_mismatch":
        return f"SYNTHETIC: invoice vendor is spelled differently from the PO vendor ({VENDORS[p.vendor].po_name})."
    return {
        "checksum": "SYNTHETIC: GSTIN has the right shape but the wrong check character, a likely typo.",
        "format": "SYNTHETIC: GSTIN has a letter where a digit belongs, a likely scan error.",
        "rate_vs_po": "SYNTHETIC: invoice charges 18 percent GST while the PO was raised at 12 percent.",
    }[f.note]


SEVERITY_RANK = {"high": 0, "medium": 1, "low": 2}


def render_csv(rows: list[list[str]]) -> bytes:
    buf = io.StringIO(newline="")
    csv.writer(buf, lineterminator="\n").writerows(rows)
    return buf.getvalue().encode("utf-8")


def build_files() -> dict[str, bytes]:
    invoices = INVOICES
    pos = sorted(PURCHASE_ORDERS, key=lambda p: (p.day, p.no))
    payment_rows = build_payment_rows(invoices)
    found = reference_exceptions(invoices, pos, payment_rows)
    check_invariants(invoices, pos, payment_rows, found)

    by_ref = {i.ref: i for i in invoices}
    pos_by_no = {p.no: p for p in pos}

    # invoices.csv: marker, two preamble lines, header, 40 rows, Grand Total footer
    inv_rows = [[MARKER], [BUYER], ["Purchase Register 1-Apr-2024 to 31-Mar-2025"], INVOICE_HEADER]
    first_data_line = len(inv_rows) + 1
    inv_rows += [invoice_cells(i) for i in invoices]
    footer = [""] * len(INVOICE_HEADER)
    footer[2] = "Grand Total"
    footer[8] = money(sum((i.taxable for i in invoices), Decimal(0)), "in2")
    footer[10] = money(sum((i.gst_amount for i in invoices), Decimal(0)), "in2")
    footer[11] = money(sum((i.total for i in invoices), Decimal(0)), "in2")
    inv_rows.append(footer)
    line_of = {i.ref: first_data_line + n for n, i in enumerate(invoices)}

    po_rows = [[MARKER], PO_HEADER] + [po_cells(p) for p in pos]
    pay_rows = [[MARKER], PAYMENT_HEADER] + [payment_cells(k, r, by_ref) for k, r in enumerate(payment_rows)]

    key_rows = [KEY_HEADER]
    for f in sorted(found, key=lambda f: (-f.risk, SEVERITY_RANK[f.severity], f.invoice.no)):
        key_rows.append([
            f.type, f.invoice.no, f.invoice.party, f.po_no, ";".join(f.payment_refs),
            str(line_of[f.invoice.ref]), f"{q2(f.risk):.2f}", f.severity, planted_note(f, pos_by_no),
        ])  # fmt: skip

    return {
        "invoices.csv": render_csv(inv_rows),
        "purchase_orders.csv": render_csv(po_rows),
        "payments.csv": render_csv(pay_rows),
        "expected_exceptions.csv": render_csv(key_rows),
    }


def write_all(out_dir: Path) -> None:
    files = build_files()
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        (out_dir / name).write_bytes(data)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Write the synthetic exception-triage sample data.")
    parser.add_argument("--out", type=Path, default=Path(__file__).resolve().parent, help="output directory")
    args = parser.parse_args(argv)
    write_all(args.out)
    print(f"wrote 4 files to {args.out}")


if __name__ == "__main__":
    main()
