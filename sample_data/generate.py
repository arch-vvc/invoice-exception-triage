def date_cell(d: date, style: str) -> str:
    if style == "xl":  # Excel serial number, epoch 1899-12-30
        return str((d - date(1899, 12, 30)).days)
    return d.strftime(DATE_FORMATS[style])


def qty_cell(q: Decimal, unit: str, style: str) -> str:
    whole = q == q.to_integral_value()
    text = f"{int(q):,}" if whole else f"{q.normalize():,}"
    return f"{text} {unit}" if style == "u" else text


def gst_cell(rate: Decimal, style: str) -> str:
    n = int(rate) if rate == rate.to_integral_value() else rate.normalize()
    return {"plain": f"{n}", "pct": f"{n}%", "pct2": f"{rate:.2f} %", "igst": f"IGST {n}%"}[style]


