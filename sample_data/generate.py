def build_payment_rows(invoices):
    """Order the payments by date, number the vouchers and work out the money."""
    by_ref = {i.ref: i for i in invoices}
    staged = []
    for n, pm in enumerate(PAYMENTS):
        i = by_ref[pm.inv]
        tds = q2(i.taxable * pm.tds_pct / 100) if pm.tds_pct else Decimal(0)
        amount_paid = pm.amount if pm.amount is not None else i.total - tds
        staged.append((i.day + timedelta(days=pm.lag), n, pm, amount_paid, tds))
    staged.sort(key=lambda s: (s[0], s[1]))
    return [(f"PV/24-25/{101 + k:04d}", d, pm, paid, tds) for k, (d, _, pm, paid, tds) in enumerate(staged)]


# ---------------------------------------------------------------- reference check (contracts C3 and C5, own arithmetic)


@dataclass
class Found:
    type: str
    invoice: Invoice
    risk: Decimal
    severity: str
    po_no: str = ""
    payment_refs: tuple[str, ...] = ()
    note: str = ""  # gst reason, or the original invoice number for a duplicate


def gst_check(i: Invoice, p: PO | None) -> Found | None:
    """First hit of checks a-f in the C5 gst_error row."""
    g = i.gst / 100
    problem = gstin_problem(i.gstin_cell)
    shown = i.styles[1] not in ("", "-", "NA")  # blank gst_amount skips check f
    risk = i.gst_amount if shown else q2(i.taxable * g)
    reason = None
    if problem == "missing" and i.gst > 0:
        reason = "missing"
    elif problem in ("format", "checksum"):
        reason = problem
    elif i.gst not in SLABS:
        reason = "slab"
    elif p is not None and i.gst != p.gst:
        reason, risk = "rate_vs_po", q2(abs(i.taxable * (i.gst - p.gst) / 100))
    elif shown and abs(i.gst_amount - i.taxable * g) > tolerance(i.taxable * g):
        reason, risk = "amount", q2(abs(i.gst_amount - i.taxable * g))
    if reason is None:
        return None
    severity = "high" if reason in ("missing", "format", "checksum") else "medium"
    return Found("gst_error", i, risk, severity, p.no if p else "", note=reason)


def reference_exceptions(invoices, pos, payment_rows) -> list[Found]:
    """Apply the C3 linking order and the C5 catalogue to the literal specs."""
    found: list[Found] = []
    by_po_key = {doc_key(p.no): p for p in pos}
    pos_by_vendor: dict[str, list[PO]] = {}
    for p in pos:
        pos_by_vendor.setdefault(vendor_key(VENDORS[p.vendor].po_name), []).append(p)

    # 1. duplicates: a later row with the same vendor key, document key and a total within tolerance
    seen: dict[tuple[str, str], list[Invoice]] = {}
    duplicates: dict[str, Invoice] = {}
    for i in invoices:
        key = (vendor_key(i.party), doc_key(i.no))
        for earlier in seen.get(key, []):
            if abs(i.total - earlier.total) <= tolerance(earlier.total) and i.ref not in duplicates:
                duplicates[i.ref] = earlier
        seen.setdefault(key, []).append(i)
    for i in invoices:
        if i.ref in duplicates:
            found.append(Found("duplicate_invoice", i, i.total, "high", note=duplicates[i.ref].no))
    live = [i for i in invoices if i.ref not in duplicates]

    # 2. invoice -> PO. A wrong reference gets no fallback; a blank one needs a vendor with exactly one PO.
    linked: dict[str, PO | None] = {}
    for i in live:
        if i.po_cell.strip():
            linked[i.ref] = by_po_key.get(doc_key(i.po_cell))
        else:
            candidates = pos_by_vendor.get(vendor_key(i.party), [])
            linked[i.ref] = candidates[0] if len(candidates) == 1 else None

    # 3. per-invoice checks, quantity cumulative per PO in date order
    cumulative: dict[str, Decimal] = {}
    for i in sorted(live, key=lambda x: (x.day, invoices.index(x))):
        p = linked[i.ref]
        if p is None:
            found.append(Found("missing_po", i, i.total, "high" if i.total >= 100000 else "medium"))
        else:
            if vendor_key(i.party) != vendor_key(VENDORS[p.vendor].po_name):
                found.append(Found("vendor_name_mismatch", i, Decimal(0), "low", p.no))
            expected = q2(i.qty * p.rate)
            diff = i.taxable - expected
            if abs(diff) > tolerance(expected):
                risk = q2(abs(diff) * (1 + i.gst / 100))
                found.append(Found("amount_mismatch", i, risk, "high" if risk >= 10000 else "medium", p.no))
            cumulative[p.no] = cumulative.get(p.no, Decimal(0)) + i.qty
            if cumulative[p.no] > p.qty:
                excess = min(i.qty, cumulative[p.no] - p.qty)
                risk = q2(excess * p.rate * (1 + p.gst / 100))
                found.append(Found("quantity_mismatch", i, risk, "high" if risk >= 10000 else "medium", p.no))
        hit = gst_check(i, p)
        if hit:
            found.append(hit)

    # 4. payment -> invoice: explicit reference, else a unique payee and amount match
    by_ref = {i.ref: i for i in invoices}
    paid: dict[str, list[tuple[str, Decimal]]] = {}
    for pid, _, pm, amount_paid, tds in payment_rows:
        settled = amount_paid + tds
        if pm.bill is None or pm.bill.strip():
            key = doc_key(by_ref[pm.inv].no if pm.bill is None else pm.bill)
            target = next((i for i in live if doc_key(i.no) == key), None)
        else:
            payee = vendor_key(VENDORS[by_ref[pm.inv].vendor].payee)
            matches = [i for i in live if vendor_key(i.party) == payee and abs(i.total - settled) <= tolerance(settled)]
            target = matches[0] if len(matches) == 1 else None
        assert target is not None, f"payment {pid} would be unmatched"
        paid.setdefault(target.ref, []).append((pid, settled))

    # 5. payment checks, only for invoices with at least one payment
    for i in live:
        rows = paid.get(i.ref)
        if not rows:
            continue
        settled_sum = sum((s for _, s in rows), Decimal(0))
        refs = tuple(pid for pid, _ in rows)
        po_no = linked[i.ref].no if linked[i.ref] else ""
        if 0 < settled_sum < i.total - 1:
            risk = i.total - settled_sum
            found.append(Found("partial_payment", i, risk, "medium" if risk >= 50000 else "low", po_no, refs))
        elif settled_sum > i.total + 1:
            found.append(Found("overpayment", i, settled_sum - i.total, "high", po_no, refs))

    # A duplicate lists the PO and payments of the invoice it repeats, so the key shows what was already paid.
    for n, f in enumerate(found):
        if f.type == "duplicate_invoice":
            original = duplicates[f.invoice.ref]
            po = linked.get(original.ref)
            refs = tuple(pid for pid, _ in paid.get(original.ref, []))
            found[n] = replace(f, po_no=po.no if po else "", payment_refs=refs)
    return found


def check_invariants(invoices, pos, payment_rows, found):
    assert len(invoices) == 40 and len(pos) == 30 and len(payment_rows) == 35

    keys = [doc_key(i.no) for i in invoices]
    dup_keys = {doc_key("INV-0042"), doc_key("SE/24-25/0107")}
    for k in set(keys):
        assert keys.count(k) == (2 if k in dup_keys else 1), f"document key collision on {k}"
    assert len({doc_key(p.no) for p in pos}) == 30
    assert len({r[0] for r in payment_rows}) == 35

    # exactly the planted exceptions fire, and no invoice triggers two types
    assert sorted((f.type, f.invoice.ref) for f in found) == sorted(PLANTED)
    assert len({f.invoice.ref for f in found}) == len(found) == 16
    gst_reasons = {f.invoice.ref: f.note for f in found if f.type == "gst_error"}
    assert gst_reasons == {"I21": "rate_vs_po", "I32": "checksum", "I33": "format"}

    settled: dict[str, Decimal] = {}
    for _, _, pm, paid, tds in payment_rows:
        settled[pm.inv] = settled.get(pm.inv, Decimal(0)) + paid + tds

    by_po = {doc_key(p.no): p for p in pos}
    planted = {f.invoice.ref for f in found}
    for i in invoices:
        assert abs(i.total - (i.taxable + i.gst_amount)) <= Decimal("0.50"), i.no
        assert i.gst in SLABS, i.no
        assert FY_START <= i.day <= FY_END, i.no
        assert gstin_problem(i.gstin_cell) == BAD_GSTIN_REASON.get(i.ref), i.no
        if i.po_cell.strip() and doc_key(i.po_cell) in by_po:
            assert by_po[doc_key(i.po_cell)].day <= i.day, f"{i.no} predates its PO"
        if i.ref not in planted and i.ref in settled:
            assert abs(settled[i.ref] - i.total) <= 1, f"clean invoice {i.no} does not settle in full"
    for p in pos:
        assert gstin_problem(VENDORS[p.vendor].gstin) is None and p.gst in SLABS
        assert FY_START <= p.day <= FY_END
    for _, d, *_ in payment_rows:
        assert FY_START <= d <= FY_END, d


