@dataclass(frozen=True)
class Invoice:
    ref: str  # our own label, never written to a file
    no: str
    vendor: str
    day: date
    po_cell: str  # exactly what the Order No cell says
    item: str
    qty: Decimal
    unit: str
    rate: Decimal
    gst: Decimal
    name: str | None = None  # party name if it differs from the vendor's usual spelling
    gstin: str | None = None  # GSTIN cell if it differs from the vendor's real one
    roundoff: bool = False  # Tally rounds the invoice amount to the nearest rupee
    dstyle: str = "dby-"
    qstyle: str = "u"
    gstyle: str = "plain"
    styles: tuple[str, str, str] = ("in2", "in2", "in2")  # taxable, tax amount, invoice amount
    rstyle: str = "in2"  # rate cell; "", "-" or "NA" leaves it empty
    blank: tuple[str, ...] = ()  # optional cells left empty: item

    @property
    def taxable(self) -> Decimal:
        return q2(self.qty * self.rate)

    @property
    def gst_amount(self) -> Decimal:
        return q2(self.taxable * self.gst / 100)

    @property
    def total(self) -> Decimal:
        exact = self.taxable + self.gst_amount
        return exact.quantize(ONE, ROUND_HALF_UP) if self.roundoff else exact

    @property
    def party(self) -> str:
        return self.name or VENDORS[self.vendor].inv_name

    @property
    def gstin_cell(self) -> str:
        return self.gstin or VENDORS[self.vendor].gstin


def inv(ref, no, vendor, iso, po_cell, item, qty, unit, rate, gst, **kw) -> Invoice:
    return Invoice(ref, no, vendor, day(iso), po_cell, item, D(qty), unit, D(rate), D(gst), **kw)


